export type IconName = keyof typeof ICONS;

function path(rows: readonly string[]): string {
  return rows
    .flatMap((row, y) => [...row].map((cell, x) => (cell === "#" ? `M${x} ${y}h1v1h-1z` : "")))
    .join("");
}

const PATHS = Object.fromEntries(Object.entries(ICONS).map(([name, rows]) => [name, path(rows)])) as Record<IconName, string>;

export function Icon({ name, size = 12, className = "" }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg
      className={`icon ${className}`}
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      <path d={PATHS[name]} />
    </svg>
  );
}
